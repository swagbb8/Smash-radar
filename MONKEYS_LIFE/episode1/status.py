"""Writes MONKEYS_LIFE/status/: STATUS.md (every shot's state) + the review sheets, for outside reviewers (ChatGPT) on GitHub.
    python status.py            (reads the shot folders under Videos/MonkeysLife/ai, never the cloud)
States: no keyframe / keyframe waiting review / keyframe rejected / keyframe approved / clip rejected / clip approved.
"""
import json, os, shutil
from PIL import Image
import ai_scene

AI = os.path.join(os.path.expanduser('~'), 'Videos', 'MonkeysLife', 'ai')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'status')
SCENES = [('ep1_lab', 'SCENE1', 'scene1', 'Scene 1 — The Lab')]          # grows as scenes go into production


def state(folder, name, verdicts):
    v = verdicts.get(name)
    if not os.path.exists(os.path.join(folder, name + '.jpg')): return 'no keyframe', ''
    if v is None: return 'keyframe waiting review', ''
    if not v['ok']: return 'keyframe REJECTED', v['why']
    c = v.get('clip')
    if c is None: return 'keyframe approved', v['why']
    return ('clip APPROVED' if c['ok'] else 'clip REJECTED'), c['why']


def main():
    os.makedirs(OUT, exist_ok=True)
    md = ['# Monkey\'s Life — shot status', '',
          'Generated by `episode1/status.py`. Facts only: a shot is APPROVED after its picture or clip was actually looked at.',
          'Reviewers: open a GitHub issue titled with the shot ID (e.g. "B03: ...") to request a change.', '']
    total = done = 0
    for module, lst, sub, title in SCENES:
        folder = os.path.join(AI, sub)
        verdicts = json.load(open(os.path.join(folder, 'review.json'))) if os.path.exists(os.path.join(folder, 'review.json')) else {}
        shots = ai_scene.shots(module, lst)
        md += [f'## {title}', '', '| Shot | Sec | Action (script) | State | Note |', '|---|---|---|---|---|']
        for s in shots:
            st, why = state(folder, s['name'], verdicts); total += s['dur']; done += s['dur'] * (st == 'clip APPROVED')
            md.append(f"| {s['name']} | {s['dur']:.1f} | {s['act'][:70].replace('|', '/')} | {st} | {why.replace('|', '/')} |")
        sheet = os.path.join(folder, f'review_{sub}.jpg')
        if os.path.exists(sheet):
            im = Image.open(sheet); im.thumbnail((1280, 4000)); im.save(os.path.join(OUT, f'review_{sub}.jpg'), quality=80)
            md += ['', f'![review sheet](review_{sub}.jpg)', '']
    md.insert(4, f'**Approved footage: {done / 60:.1f} of {total / 60:.1f} planned minutes in production.**\n')
    open(os.path.join(OUT, 'STATUS.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    prod = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'PRODUCTION.md')
    print('wrote', os.path.normpath(OUT), os.path.exists(prod))


if __name__ == '__main__':
    main()
